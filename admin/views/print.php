<?php
/**
 * Standalone, print-optimized document for PDF export.
 *
 * @package CoreA11y
 * @var string $type     'report' or 'compare'.
 * @var string $title    Document title.
 * @var array  $data     Variables for the body partial.
 */

defined( 'ABSPATH' ) || exit;

$corea11y_is_print = true;
$corea11y_site     = get_bloginfo( 'name' );
$corea11y_host     = wp_parse_url( home_url(), PHP_URL_HOST );
// phpcs:ignore WordPress.PHP.DontExtract.extract_extract -- Controlled, internal variables only.
extract( $data, EXTR_SKIP );
?>
<!DOCTYPE html>
<html <?php language_attributes(); ?>>
<head>
	<meta charset="<?php bloginfo( 'charset' ); ?>">
	<meta name="viewport" content="width=device-width, initial-scale=1">
	<title><?php echo esc_html( $title . ' · ' . $corea11y_site ); ?></title>
	<?php wp_print_styles( array( 'corea11y-admin', 'corea11y-print' ) ); ?>
	<?php
	/** This filter is documented below. */
	$corea11y_brand_head = (array) apply_filters( 'corea11y_report_brand', array( 'name' => 'CoreA11y', 'logo' => '' ) );
	$corea11y_color      = isset( $corea11y_brand_head['color'] ) ? sanitize_hex_color( $corea11y_brand_head['color'] ) : '';
	$corea11y_white      = ! empty( $corea11y_brand_head['logo'] ) || ( isset( $corea11y_brand_head['name'] ) && 'CoreA11y' !== $corea11y_brand_head['name'] );
	if ( $corea11y_white ) :
		// White label: their color (if any), with readable text picked automatically. Otherwise neutral charcoal.
		$corea11y_vars = $corea11y_color ? CoreA11y_UI::brand_css_vars( $corea11y_color ) : '--corea11y-stripe:#222222;--corea11y-ring:#ffffff;--corea11y-ring-track:rgba(255,255,255,.28);';
		?>
		<style>.corea11y-print{<?php echo esc_html( $corea11y_vars ); ?>}</style>
	<?php endif; ?>
</head>
<body class="corea11y corea11y-print<?php echo $corea11y_white ? ' is-white-label' : ''; ?>">
	<div class="corea11y-print-bar" role="region" aria-label="<?php esc_attr_e( 'Export', 'corea11y' ); ?>">
		<p><?php esc_html_e( 'In the print window, choose "Save as PDF" as the destination.', 'corea11y' ); ?></p>
		<button type="button" class="button button-primary" id="corea11y-print-now"><?php esc_html_e( 'Save as PDF', 'corea11y' ); ?></button>
	</div>

	<main class="corea11y-doc">
		<header class="corea11y-doc-head">
			<?php
			/**
			 * Filter the brand shown at the top of PDF reports (CoreA11y Pro Agency: white label).
			 *
			 * @param array $brand { name: string, logo: string (image URL, optional) }.
			 */
			$corea11y_brand = (array) apply_filters( 'corea11y_report_brand', array( 'name' => 'CoreA11y', 'logo' => '' ) );
			?>
			<div class="corea11y-brand">
				<?php if ( ! empty( $corea11y_brand['logo'] ) ) : ?>
					<img class="corea11y-brand-logo" src="<?php echo esc_url( $corea11y_brand['logo'] ); ?>" alt="<?php echo esc_attr( isset( $corea11y_brand['name'] ) ? $corea11y_brand['name'] : '' ); ?>">
				<?php elseif ( $corea11y_white ) : ?>
					<span class="corea11y-brand-name"><?php echo esc_html( $corea11y_brand['name'] ); ?></span>
				<?php else : ?>
					<?php echo CoreA11y_UI::logo_mark( 34 ) . CoreA11y_UI::wordmark(); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Static markup. ?>
				<?php endif; ?>
			</div>
			<div class="corea11y-doc-site">
				<strong><?php echo esc_html( $corea11y_site ); ?></strong><br>
				<span><?php echo esc_html( $corea11y_host ); ?></span>
			</div>
		</header>

		<h1 class="corea11y-doc-title"><?php echo esc_html( $title ); ?></h1>
		<p class="corea11y-meta">
			<?php
			/* translators: %s: date the PDF was generated. */
			echo esc_html( sprintf( __( 'Generated %s', 'corea11y' ), wp_date( get_option( 'date_format' ) . ' ' . get_option( 'time_format' ) ) ) );
			?>
		</p>

		<?php
		if ( 'compare' === $type ) {
			require COREA11Y_DIR . 'admin/views/partials/compare-body.php';
		} else {
			require COREA11Y_DIR . 'admin/views/partials/report-body.php';
		}
		?>

		<footer class="corea11y-doc-foot">
			<?php
			/* translators: %s: plugin version. */
			$corea11y_foot = sprintf( __( 'Report generated by CoreA11y %s · Automated results do not certify WCAG conformance.', 'corea11y' ), COREA11Y_VERSION );
			/**
			 * Filter the footer line of PDF reports.
			 *
			 * @param string $foot Footer text.
			 */
			echo esc_html( apply_filters( 'corea11y_report_footer', $corea11y_foot ) );
			?>
		</footer>
	</main>
	<?php
	wp_print_inline_script_tag(
		"document.getElementById('corea11y-print-now').addEventListener('click',function(){window.print();});window.addEventListener('load',function(){setTimeout(function(){window.print();},500);});"
	);
	?>
</body>
</html>
